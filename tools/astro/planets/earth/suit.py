#  胴（胸板・星核・腹・襟・脇）
# ---------------------------------------------------------------------------
def torso(s):
    c = s.part("torso", "chest", "body")
    # 胸郭: 縦の稜を落とした青い殻（上が広く、腹は細い → 逆三角形）
    bevel(c, (0, 21.1, 0.0), (9.8, 5.8, 5.8), "plate", cut=0.6, axis="y")
    cbox(c, (0, 15.9, 0.0), (7.4, 4.8, 5.2), "plate_b")                    # 腹の殻（細い）
    cbox(c, (0, 16.0, -2.62), (5.2, 4.6, 0.5), "frame")                    # 腹の下地
    # 腹: 下へ行くほど細い三段の装甲（上の段が下の段に重なる）
    for y, w in ((17.25, 5.0), (16.0, 4.6), (14.75, 4.1)):
        rbox(c, (0, y, -2.98), (w, 1.3, 0.7), "plate", rot=(-10, 0, 0),
             decals={"north": {"decal": "stripe", "dir": "v", "pos": 0.5, "width": 0.07,
                               "color": (24, 34, 52)}})
    ob = rbox(c, (-3.3, 16.0, -2.3), (1.4, 4.2, 1.0), "plate2", rot=(0, 36, -6))   # 脇腹
    mirror_x(c, ob)
    # 白い胸板（V 字）: 外へ開き、内側の端が前へ出て、下辺が中央へ下がる
    pec = rbox(c, (-2.6, 21.55, -3.05), (5.0, 4.0, 0.9), "plate2", rot=(6, 17, 9))
    trim = stick(c, pec, "north", 0.5, 0.03, (4.8, GOLD_W, 0.22), "gold", sink=0.05)
    l1 = line_on(c, pec, "north", (0.95, 0.42), (0.62, 0.58), 0.26, 0.2, "glow")
    l2 = line_on(c, pec, "north", (0.62, 0.58), (0.42, 0.88), 0.26, 0.2, "glow")
    l3 = line_on(c, pec, "north", (0.42, 0.88), (0.1, 0.92), 0.26, 0.2, "glow")
    l4 = line_on(c, pec, "north", (0.62, 0.58), (0.2, 0.42), 0.26, 0.2, "glow")
    low = rbox(c, (-2.25, 18.55, -2.85), (3.9, 1.5, 0.8), "plate", rot=(-6, 12, 13))  # 胸の下の青
    mirror_x(c, pec, trim, l1, l2, l3, l4, low)
    # 襟（首の両脇に立ち上がる）
    col = rbox(c, (-3.0, 24.35, -0.2), (2.2, 1.5, 5.0), "plate", rot=(0, 0, -20))
    colt = stick(c, col, "up", 0.5, 0.5, (1.8, 4.6, 0.25), "plate2", sink=0.1)
    mirror_x(c, col, colt)
    # 星核: 黒い菱形の台 → 金の八芒の枠 → 地球 → 脈打つ光の輪
    rbox(c, (0, 20.3, -3.7), (3.6, 3.6, 0.8), "dark", rot=(0, 0, 45))
    octa(c, (0, 20.3, -4.15), 3.3, 0.4, "gold", axis="z")
    cbox(c, (0, 20.3, -4.35), (2.4, 2.4, 0.9), "core")
    gl = s.fx("glow", "core", c, pivot=(0, 20.3, -4.5))
    ring(gl, (0, 20.3, -4.5), 1.72, 8, (0, 0.3, 0.3), "glow", axis="z")
    # 脇: 白い板と排気口
    fl = cbox(c, (-4.8, 21.0, 0.3), (0.5, 3.6, 3.2), "plate2")
    fv = cbox(c, (-5.07, 20.9, 0.3), (0.15, 2.4, 2.0), "vent")
    mirror_x(c, fl, fv)


