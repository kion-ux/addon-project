    b = s.part("boots", "foot_r", "rightLeg")
    cbox(b, (X, -0.3, -0.5), (5.2, 0.8, 6.4), "frame")                  # 靴底
    cbox(b, (X, 1.7, -0.25), (5.2, 3.2, 5.7), "plate")                  # 足の殻
    toe = rbox(b, (X, 1.15, -3.15), (4.8, 2.3, 1.7), "plate2", rot=(-38, 0, 0))
    stick(b, toe, "north", 0.5, 0.55, (0.5, 1.5, 0.25), "glow", sink=0.05)
    cbox(b, (X, 0.3, -3.95), (4.6, 0.7, 0.7), "gold")                   # つま先の金具
    rbox(b, (X, 3.35, -2.5), (4.0, 2.2, 0.8), "plate2", rot=(-30, 0, 0))  # 甲
    rbox(b, (X, 1.6, 2.7), (4.6, 2.8, 0.9), "plate_b", rot=(8, 0, 0))     # 踵
    cbox(b, (X, 0.45, 3.15), (3.0, 1.0, 1.1), "frame")                  # 踵の噴射口
    cbox(b, (X, -0.05, 3.15), (2.2, 0.2, 0.7), "thruster")
    octa(b, (X - 2.72, 2.9, 0.2), 2.0, 0.55, "chrome", axis="x")        # 足首の関節（外）
    octa(b, (X - 3.0, 2.9, 0.2), 0.9, 0.3, "glow", axis="x")
    cbox(b, (X - 2.66, 0.95, -0.7), (0.22, 0.35, 4.2), "glow")          # 外側の発光線


