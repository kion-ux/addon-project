    g = s.part("legs", "greave_r", "rightLeg")
    cbox(g, (X, 5.2, 0.05), (5.3, 4.4, 5.5), "plate")                   # 脛の殻
    keel = rbox(g, (X - 0.72, 5.0, -2.95), (1.55, 4.2, 0.8), "plate2", rot=(0, 22, 0))
    mirror_x(g, keel, about=X)                                           # 脛の稜（V 字）
    # 大陸の線（脛の稜の上を折れ線で）
    line_on(g, keel, "north", (0.25, 0.1), (0.55, 0.45), 0.26, 0.2, "glow")
    line_on(g, keel, "north", (0.55, 0.45), (0.4, 0.9), 0.26, 0.2, "glow")
    cbox(g, (X, 8.1, 0.05), (5.25, 1.5, 5.35), "frame")                  # 膝の関節
    # 膝当て: 面取りした板 + 上の庇 + 菱形の宝玉 + 金の下縁
    bevel(g, (X, 7.45, -3.0), (3.6, 2.8, 1.2), "plate2", cut=0.5, axis="z")
    rbox(g, (X, 8.95, -2.7), (3.1, 1.0, 1.1), "plate", rot=(30, 0, 0))
    rbox(g, (X, 7.45, -3.72), (1.0, 1.0, 0.5), "gem", rot=(0, 0, 45))
    cbox(g, (X, 6.15, -3.5), (3.0, GOLD_W, 0.5), "gold")
