def legs(s):
    X = LEG_X
    g = s.part("legs", "greave_r", "rightLeg")
    cbox(g, (X, 5.2, 0.05), (5.3, 4.4, 5.5), "plate")                   # 脛の殻
    keel = rbox(g, (X - 0.72, 5.0, -2.95), (1.55, 4.2, 0.8), "plate2", rot=(0, 22, 0))
    mirror_x(g, keel, about=X)                                           # 脛の稜（V 字）
    # 大陸の線（脛の稜の上を折れ線で）
    line_on(g, keel, "north", (0.25, 0.1), (0.55, 0.45), 0.26, 0.2, "glow")
    line_on(g, keel, "north", (0.55, 0.45), (0.4, 0.9), 0.26, 0.2, "glow")
    # 膝当て: 面取りした板 + 上の庇 + 菱形の宝玉 + 金の下縁
    bevel(g, (X, 7.45, -3.0), (3.6, 2.8, 1.2), "plate2", cut=0.5, axis="z")
    rbox(g, (X, 8.95, -2.7), (3.1, 1.0, 1.1), "plate", rot=(30, 0, 0))
    rbox(g, (X, 7.45, -3.72), (1.0, 1.0, 0.5), "gem", rot=(0, 0, 45))
    cbox(g, (X, 6.15, -3.5), (3.0, GOLD_W, 0.5), "gold")
    # ふくらはぎ・排気口
    calf = rbox(g, (X, 5.4, 2.85), (4.6, 4.2, 1.0), "plate_b", rot=(-8, 0, 0))
    stick(g, calf, "south", 0.5, 0.5, (2.6, 2.4, 0.3), "vent", sink=0.1)
    # 外側のヒレ（上端が外へ）
    fin = rbox(g, (X - 2.75, 5.8, 0.8), (0.7, 4.0, 3.2), "plate2", rot=(-10, 0, -8))
    line_on(g, fin, "west", (0.15, 0.3), (0.85, 0.75), 0.24, 0.2, "glow")
    # 腿
    t = s.part("legs", "thigh_r", "rightLeg", pivot=(X, 11.6, 0))
    cbox(t, (X, 10.4, 0.05), (5.2, 3.3, 5.4), "plate_b")
    th = rbox(t, (X, 10.35, -2.85), (4.4, 3.4, 0.8), "plate", rot=(-5, 0, 0))
    line_on(t, th, "north", (0.78, 0.1), (0.78, 0.6), 0.26, 0.2, "glow")
    line_on(t, th, "north", (0.78, 0.6), (0.55, 0.9), 0.26, 0.2, "glow")
    cbox(t, (X, 8.75, -2.9), (4.2, GOLD_W, 0.6), "gold")
    side = cbox(t, (X - 2.62, 10.2, 0.3), (0.6, 3.0, 3.8), "plate2",
                decals={"west": {"decal": "serial", "text": "GA-03", "ink": (40, 60, 110)}})
    del side


