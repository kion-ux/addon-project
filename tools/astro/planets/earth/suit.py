#  胴（胸板・星核・腹・襟・脇）
# ---------------------------------------------------------------------------
def torso(s):
    c = s.part("torso", "chest", "body")
    cbox(c, (0, 18.7, 0.0), (9.3, 10.2, 5.6), "plate")                   # 胴の殻
    cbox(c, (0, 15.4, -2.75), (5.6, 3.8, 0.5), "frame")                  # 腹の下地
    for i, y in enumerate((16.5, 15.3, 14.1)):                            # 腹筋の板
        a = cbox(c, (-1.25, y, -3.05), (2.1 - i * 0.15, 1.0, 0.6), "plate")
        mirror_x(c, a)
    pec = rbox(c, (-2.35, 20.6, -3.0), (4.6, 4.8, 0.9), "plate2", rot=(6, 12, 0))
    trim = stick(c, pec, "north", 0.5, 0.03, (4.4, GOLD_W, 0.22), "gold", sink=0.05)
    l1 = line_on(c, pec, "north", (0.95, 0.5), (0.6, 0.62), 0.26, 0.2, "glow")
    l2 = line_on(c, pec, "north", (0.6, 0.62), (0.38, 0.9), 0.26, 0.2, "glow")
    l3 = line_on(c, pec, "north", (0.38, 0.9), (0.1, 0.94), 0.26, 0.2, "glow")
    l4 = line_on(c, pec, "north", (0.9, 0.28), (0.5, 0.2), 0.26, 0.2, "glow")
    l5 = line_on(c, pec, "north", (0.5, 0.2), (0.25, 0.32), 0.26, 0.2, "glow")
    mirror_x(c, pec, trim, l1, l2, l3, l4, l5)
    # 星核: 黒い八角の台座 → 金の輪 → 地球
    octa(c, (0, 20.2, -3.75), 4.0, 0.8, "dark", axis="z")
    octa(c, (0, 20.2, -4.2), 3.3, 0.4, "gold", axis="z")
    cbox(c, (0, 20.2, -4.35), (2.4, 2.4, 0.9), "core")
    gl = s.fx("glow", "core", c, pivot=(0, 20.2, -4.5))
    ring(gl, (0, 20.2, -4.5), 1.72, 8, (0, 0.3, 0.3), "glow", axis="z")
    # 襟（後ろ）と肩の上面
    rbox(c, (0, 24.15, 2.35), (7.2, 1.6, 1.0), "plate2", rot=(-15, 0, 0))
    sh = cbox(c, (-3.2, 24.0, 0.1), (2.4, 0.8, 5.0), "plate2")
    mirror_x(c, sh)
    # 脇: 白い板と排気口
    fl = cbox(c, (-4.75, 17.5, 0.2), (0.5, 4.0, 3.4), "plate2")
    fv = cbox(c, (-5.02, 17.3, 0.2), (0.15, 2.6, 2.2), "vent")
    mirror_x(c, fl, fv)


