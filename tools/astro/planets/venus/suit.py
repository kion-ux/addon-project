def puff(bone, c, r, style):
    """角を落とした玉（7 個）。雲の一つ。"""
    d = 2 * r
    cbox(bone, c, (d * 0.66,) * 3, style)
    for ax in range(3):
        sz = [d * 0.46] * 3
        sz[ax] = d
        cbox(bone, c, sz, style)
    for rot_, ax in (((45, 0, 0), 0), ((0, 45, 0), 1), ((0, 0, 45), 2)):
        sz = [d * 0.66] * 3
        sz[ax] = d * 0.86
        rbox(bone, c, sz, style, rot=rot_)


