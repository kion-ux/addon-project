from __future__ import annotations

import math


def arc(phi, x=0.0, r=7.2):
    """胸の前の弧の上の点（胸の座標）。phi: 0 = 肩の高さの正面、90 = 頭上、180 = 背中側、負は下。"""
    a = math.radians(phi)
    return (float(x), 22.0 + r * math.sin(a), -r * math.cos(a))


def unit(*v):
    n = math.sqrt(sum(c * c for c in v)) or 1.0
    return tuple(c / n for c in v)


